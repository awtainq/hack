import pandas as pd
import numpy as np

print("=== REGISTERED ===")
df_reg = pd.read_csv('processed_data/registered.csv')
print(df_reg.info())
print(df_reg.head())
print("Nulls:\n", df_reg.isnull().sum())
print("zayav_type_name:\n", df_reg['zayav_type_name'].value_counts())
print("priem_doc_type_name:\n", df_reg['priem_doc_type_name'].value_counts())
df_reg['reg_ts'] = pd.to_datetime(df_reg['reg_ts'])
print("reg_ts range:", df_reg['reg_ts'].min(), "to", df_reg['reg_ts'].max())
print("Years in reg:\n", df_reg['reg_ts'].dt.year.value_counts().sort_index())

print("\n=== INCLUDED IN KS ===")
df_ks = pd.read_csv('processed_data/included_ks.csv')
print(df_ks.info())
print(df_ks.head())
print("Nulls:\n", df_ks.isnull().sum())
print("ob_osnova_name:\n", df_ks['ob_osnova_name'].value_counts(dropna=False))
print("ob_osnova_kod vs name:\n", df_ks[['ob_osnova_kod', 'ob_osnova_name']].drop_duplicates())
print("zayav_type_name:\n", df_ks['zayav_type_name'].value_counts())
print("priem_doc_type_name:\n", df_ks['priem_doc_type_name'].value_counts())
df_ks['reg_ts'] = pd.to_datetime(df_ks['reg_ts'])
print("reg_ts range in ks:", df_ks['reg_ts'].min(), "to", df_ks['reg_ts'].max())
print("Years in ks:\n", df_ks['reg_ts'].dt.year.value_counts().sort_index())

print("\n=== STATUSES ===")
df_stat = pd.read_csv('processed_data/statuses.csv')
print(df_stat.info())
print(df_stat.head())
print("Nulls:\n", df_stat.isnull().sum())
print("zayav_status_name:\n", df_stat['zayav_status_name'].value_counts())
print("priem_doc_type_name:\n", df_stat['priem_doc_type_name'].value_counts())
df_stat['ts_reg'] = pd.to_datetime(df_stat['ts_reg'])
df_stat['ts_reject'] = pd.to_datetime(df_stat['ts_reject'])
print("ts_reg range in stat:", df_stat['ts_reg'].min(), "to", df_stat['ts_reg'].max())
print("ts_reject count non-null:", df_stat['ts_reject'].notnull().sum())
print("Years in stat:\n", df_stat['ts_reg'].dt.year.value_counts().sort_index())

print("\n=== COMPARISON BETWEEN DATASETS ===")
# Check overlap of abitur_kod
abit_reg = set(df_reg['abitur_kod'])
abit_ks = set(df_ks['abitur_kod'])
abit_stat = set(df_stat['abitur_kod'])
print(f"Unique abit in reg: {len(abit_reg)}")
print(f"Unique abit in ks: {len(abit_ks)}")
print(f"Unique abit in stat: {len(abit_stat)}")
print(f"Overlap reg & ks: {len(abit_reg & abit_ks)}")
print(f"Overlap ks & stat: {len(abit_ks & abit_stat)}")
print(f"Overlap reg & stat: {len(abit_reg & abit_stat)}")

